const REPORT_FONT_URL = '/fonts/olitechs-report-sans.ttf';
const FONT_VFS_NAME = 'OliTechsReportSans.ttf';
const FONT_FAMILY = 'OliTechsReportSans';
let fontPromise;

const COLOR_TOKENS = {
  deepLagoon: '--deep-lagoon',
  coastalTeal: '--coastal-teal',
  white: '--white',
  softWhite: '--soft-white',
  sidebar: '--sidebar',
  text: '--text',
  accent: '--accent',
  success: '--status-paid',
  danger: '--status-not-paid',
};

const requireReport = (definition) => {
  if (!definition?.key || !definition?.title || !Array.isArray(definition.sections) || !definition.sections.length) {
    throw new Error('A complete report definition is required.');
  }
  return definition;
};

export const safeReportText = (value) => String(value ?? '').replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F]/g, ' ').trim();

export const escapeSpreadsheetFormula = (value) => {
  const text = safeReportText(value);
  return /^[\s\uFEFF]*[=+@\-]/.test(text) ? `'${text}` : text;
};

const rgbToHex = (value) => {
  if (/^#[0-9a-f]{6}$/i.test(value)) return value.slice(1).toUpperCase();
  if (/^#[0-9a-f]{3}$/i.test(value)) return value.slice(1).split('').map((part) => part + part).join('').toUpperCase();
  const match = String(value).match(/rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)/i);
  if (match) return match.slice(1, 4).map((part) => Number(part).toString(16).padStart(2, '0')).join('').toUpperCase();
  throw new Error(`The Coastal Linen document token is not a supported RGB color: ${value}`);
};

const colorToRgb = (value) => {
  const hex = rgbToHex(value);
  return [0, 2, 4].map((offset) => parseInt(hex.slice(offset, offset + 2), 16));
};

export function resolveReportTheme(overrides) {
  if (overrides) return { ...overrides };
  if (typeof document === 'undefined' || typeof getComputedStyle !== 'function') {
    throw new Error('The report theme is unavailable. Supply CSS-token colors when rendering outside the application.');
  }
  const theme = {};
  Object.entries(COLOR_TOKENS).forEach(([name, token]) => {
    const probe = document.createElement('span');
    probe.style.color = `var(${token})`;
    probe.setAttribute('aria-hidden', 'true');
    probe.style.position = 'absolute';
    probe.style.visibility = 'hidden';
    document.body.appendChild(probe);
    const computed = getComputedStyle(probe).color;
    probe.remove();
    theme[name] = `#${rgbToHex(computed)}`;
  });
  return theme;
}

const toExcelDate = (value) => {
  if (value instanceof Date) return Number.isNaN(value.getTime()) ? null : value;
  const date = new Date(value);
  return Number.isNaN(date.getTime()) ? safeReportText(value) : date;
};

const cellValueFor = (column, value) => {
  if (value === null || value === undefined || value === '') return null;
  if (column.type === 'number') {
    const number = Number(value);
    return Number.isFinite(number) ? number : null;
  }
  if (column.type === 'date' || column.type === 'datetime') return toExcelDate(value);
  return escapeSpreadsheetFormula(value);
};

const excelNumberFormat = (format) => ({
  currency: '"KES" #,##0.00;[Red]("KES" #,##0.00)',
  quantity: '#,##0.###;[Red](#,##0.###)',
  number: '#,##0.00;[Red](#,##0.00)',
  percent: '0.0%',
  date: 'dd mmm yyyy',
  datetime: 'dd mmm yyyy hh:mm',
}[format] || 'General');

const colLetter = (index) => {
  let number = index;
  let result = '';
  while (number > 0) {
    const remainder = (number - 1) % 26;
    result = String.fromCharCode(65 + remainder) + result;
    number = Math.floor((number - 1) / 26);
  }
  return result;
};

const colorARGB = (value) => {
  const hex = rgbToHex(value.startsWith('#') ? value : `#${value}`);
  return `FF${hex}`;
};

const workbookSummaryRows = (definition) => {
  const metadata = [
    ['Report', definition.title],
    ['Business', definition.propertyName || 'OliTechs'],
    ['Period', definition.period?.from && definition.period?.to ? `${definition.period.from} to ${definition.period.to}` : 'Current'],
    ['Generated by', definition.generatedBy || 'Authorized user'],
    ['Generated at', definition.generatedAt || new Date().toISOString()],
    ['Rows', definition.rowCount ?? definition.sections.reduce((sum, section) => sum + (section.rows?.length || 0), 0)],
  ];
  Object.entries(definition.filters || {}).forEach(([key, value]) => {
    if (value !== undefined && value !== null && value !== '') metadata.push([`Filter · ${key}`, Array.isArray(value) ? value.join(', ') : String(value)]);
  });
  const summary = (definition.summary || []).map((item) => [item.label, cellValueFor({ type: item.format === 'currency' || item.format === 'number' || item.format === 'quantity' ? 'number' : 'text' }, item.value), item.format || '']);
  return { metadata, summary };
};

function addWorksheet(workbook, section, definition, theme, landscape) {
  const safeName = String(section.name || 'Report').replace(/[\\/*?:\[\]]/g, ' ').slice(0, 31) || 'Report';
  const worksheet = workbook.addWorksheet(safeName);
  const columns = section.columns || [];
  if (!columns.length) throw new Error(`Report section “${section.title}” has no columns.`);
  const columnCount = columns.length;
  const endColumn = colLetter(columnCount);
  worksheet.mergeCells(`A1:${endColumn}1`);
  worksheet.getCell('A1').value = escapeSpreadsheetFormula(definition.title);
  worksheet.getCell('A1').font = { name: 'Aptos Display', size: 16, bold: true, color: { argb: colorARGB(theme.deepLagoon) } };
  worksheet.getCell('A1').alignment = { vertical: 'middle' };
  worksheet.getRow(1).height = 28;
  worksheet.mergeCells(`A2:${endColumn}2`);
  worksheet.getCell('A2').value = escapeSpreadsheetFormula(section.title || definition.subtitle || 'Report data');
  worksheet.getCell('A2').font = { name: 'Aptos', size: 11, color: { argb: colorARGB(theme.coastalTeal) } };
  worksheet.mergeCells(`A3:${endColumn}3`);
  worksheet.getCell('A3').value = escapeSpreadsheetFormula(`${definition.propertyName || 'OliTechs'} · ${definition.period?.from || 'Current'}${definition.period?.to ? ` to ${definition.period.to}` : ''}`);
  worksheet.getCell('A3').font = { name: 'Aptos', size: 9, color: { argb: colorARGB(theme.text) } };
  worksheet.mergeCells(`A4:${endColumn}4`);
  const filterSummary = Object.entries(definition.filters || {}).filter(([, value]) => value !== null && value !== undefined && value !== '').map(([key, value]) => `${key}: ${Array.isArray(value) ? value.join(', ') : value}`).join(' · ');
  worksheet.getCell('A4').value = escapeSpreadsheetFormula(`Generated by ${definition.generatedBy || 'Authorized user'} · ${new Date(definition.generatedAt || Date.now()).toLocaleString('en-KE')}${filterSummary ? ` · ${filterSummary}` : ''}`);
  worksheet.getCell('A4').font = { name: 'Aptos', size: 8, color: { argb: colorARGB(theme.text) } };

  const headerRow = 6;
  const header = worksheet.getRow(headerRow);
  header.values = columns.map((column) => escapeSpreadsheetFormula(column.label));
  header.height = 24;
  header.eachCell((cell) => {
    cell.font = { name: 'Aptos', size: 10, bold: true, color: { argb: colorARGB(theme.white) } };
    cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: colorARGB(theme.deepLagoon) } };
    cell.alignment = { vertical: 'middle', wrapText: true };
    cell.border = { bottom: { style: 'thin', color: { argb: colorARGB(theme.coastalTeal) } } };
  });

  const dataRows = Array.isArray(section.rows) ? section.rows : [];
  const firstDataRow = headerRow + 1;
  dataRows.forEach((row, rowIndex) => {
    const cells = columns.map((column) => cellValueFor(column, row[column.key]));
    const excelRow = worksheet.addRow(cells);
    excelRow.height = 20;
    excelRow.eachCell({ includeEmpty: true }, (cell, columnIndex) => {
      const column = columns[columnIndex - 1];
      cell.font = { name: 'Aptos', size: 10, color: { argb: colorARGB(theme.text) } };
      if (rowIndex % 2 === 1) cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: colorARGB(theme.softWhite) } };
      cell.alignment = { vertical: 'top', wrapText: true, horizontal: column.align || (column.type === 'number' ? 'right' : 'left') };
      if (column.type === 'number' && column.format) cell.numFmt = excelNumberFormat(column.format);
      if ((column.type === 'date' || column.type === 'datetime') && column.format) cell.numFmt = excelNumberFormat(column.format);
    });
  });
  if (!dataRows.length) {
    worksheet.mergeCells(`A${firstDataRow}:${endColumn}${firstDataRow}`);
    worksheet.getCell(`A${firstDataRow}`).value = 'No transaction data for the selected filters.';
    worksheet.getCell(`A${firstDataRow}`).font = { name: 'Aptos', size: 10, italic: true, color: { argb: colorARGB(theme.text) } };
  }

  const totalColumns = columns.map((column, index) => ({ column, index: index + 1 })).filter(({ column }) => column.total === 'sum');
  let lastRow = Math.max(firstDataRow, headerRow + dataRows.length);
  if (totalColumns.length && dataRows.length) {
    const totalRow = worksheet.addRow(columns.map((column, index) => {
      if (column.total !== 'sum') return index === 0 ? 'Total' : null;
      const letter = colLetter(index + 1);
      return { formula: `SUM(${letter}${firstDataRow}:${letter}${headerRow + dataRows.length})` };
    }));
    totalRow.font = { name: 'Aptos', size: 10, bold: true, color: { argb: colorARGB(theme.deepLagoon) } };
    totalRow.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: colorARGB(theme.sidebar) } };
    totalRow.eachCell((cell, columnIndex) => {
      const column = columns[columnIndex - 1];
      if (column.type === 'number' && column.format) cell.numFmt = excelNumberFormat(column.format);
    });
    lastRow = totalRow.number;
  }

  columns.forEach((column, index) => {
    const excelColumn = worksheet.getColumn(index + 1);
    excelColumn.width = Math.min(55, Math.max(10, Number(column.width) || 18));
  });
  worksheet.views = [{ state: 'frozen', ySplit: headerRow }];
  worksheet.autoFilter = { from: `A${headerRow}`, to: `${endColumn}${headerRow}` };
  worksheet.pageSetup = {
    paperSize: 9,
    orientation: landscape ? 'landscape' : 'portrait',
    fitToPage: true,
    fitToWidth: 1,
    fitToHeight: 0,
    horizontalDpi: 300,
    verticalDpi: 300,
    margins: { left: 0.25, right: 0.25, top: 0.45, bottom: 0.45, header: 0.2, footer: 0.2 },
  };
  worksheet.pageSetup.printTitlesRow = '1:6';
  worksheet.printArea = `A1:${endColumn}${lastRow}`;
  worksheet.headerFooter.oddFooter = '&LGenerated by OliTechs&RPage &P of &N';

  const currentColumn = columns.findIndex((column) => column.key === 'current_stock');
  const minColumn = columns.findIndex((column) => column.key === 'min_stock');
  if (dataRows.length && currentColumn >= 0 && minColumn >= 0) {
    const currentLetter = colLetter(currentColumn + 1);
    const minLetter = colLetter(minColumn + 1);
    worksheet.addConditionalFormatting({
      ref: `${currentLetter}${firstDataRow}:${currentLetter}${headerRow + dataRows.length}`,
      rules: [
        { type: 'expression', formulae: [`${currentLetter}${firstDataRow}<=0`], style: { fill: { type: 'pattern', pattern: 'solid', fgColor: { argb: colorARGB(theme.danger) } }, font: { color: { argb: colorARGB(theme.white) }, bold: true } } },
        { type: 'expression', formulae: [`AND(${currentLetter}${firstDataRow}>0,${currentLetter}${firstDataRow}<=${minLetter}${firstDataRow})`], style: { fill: { type: 'pattern', pattern: 'solid', fgColor: { argb: colorARGB(theme.accent) } } } },
      ],
    });
  }
  const metricColumn = columns.findIndex((column) => column.key === 'metric');
  const amountColumn = columns.findIndex((column) => column.key === 'amount' || /variance/i.test(column.key || ''));
  if (dataRows.length && metricColumn >= 0 && amountColumn >= 0) {
    const metricLetter = colLetter(metricColumn + 1);
    const amountLetter = colLetter(amountColumn + 1);
    const amountRange = `${amountLetter}${firstDataRow}:${amountLetter}${headerRow + dataRows.length}`;
    worksheet.addConditionalFormatting({
      ref: amountRange,
      rules: [
        { type: 'expression', formulae: [`AND($${metricLetter}${firstDataRow}="Variance",${amountLetter}${firstDataRow}<0)`], style: { fill: { type: 'pattern', pattern: 'solid', fgColor: { argb: colorARGB(theme.danger) } }, font: { color: { argb: colorARGB(theme.white) }, bold: true } } },
        { type: 'expression', formulae: [`AND($${metricLetter}${firstDataRow}="Variance",${amountLetter}${firstDataRow}>0)`], style: { fill: { type: 'pattern', pattern: 'solid', fgColor: { argb: colorARGB(theme.accent) } }, font: { color: { argb: colorARGB(theme.text) }, bold: true } } },
      ],
    });
  }
  return worksheet;
}

export async function createExcelBlob(definition, { theme: themeOverrides } = {}) {
  const report = requireReport(definition);
  const theme = resolveReportTheme(themeOverrides);
  const excelModule = await import('exceljs');
  const ExcelJS = excelModule.default || excelModule;
  const workbook = new ExcelJS.Workbook();
  workbook.creator = 'OliTechs';
  workbook.lastModifiedBy = report.generatedBy || 'OliTechs';
  workbook.created = new Date(report.generatedAt || Date.now());
  workbook.modified = new Date(report.generatedAt || Date.now());
  workbook.subject = report.subtitle || report.title;
  workbook.title = report.title;
  workbook.company = report.propertyName || 'OliTechs';
  workbook.calcProperties.fullCalcOnLoad = true;

  const summarySheet = workbook.addWorksheet('Summary');
  const summaryData = workbookSummaryRows(report);
  summarySheet.mergeCells('A1:C1');
  summarySheet.getCell('A1').value = escapeSpreadsheetFormula(report.title);
  summarySheet.getCell('A1').font = { name: 'Aptos Display', size: 17, bold: true, color: { argb: colorARGB(theme.deepLagoon) } };
  summarySheet.mergeCells('A2:C2');
  summarySheet.getCell('A2').value = escapeSpreadsheetFormula(report.subtitle || 'OliTechs report');
  summarySheet.getCell('A2').font = { name: 'Aptos', size: 11, color: { argb: colorARGB(theme.coastalTeal) } };
  summaryData.metadata.forEach((row) => {
    summarySheet.addRow(row.map((value) => typeof value === 'string' ? escapeSpreadsheetFormula(value) : value));
  });
  summarySheet.addRow([]);
  if (summaryData.summary.length) {
    const header = summarySheet.addRow(['Metric', 'Value', 'Format']);
    header.font = { name: 'Aptos', bold: true, color: { argb: colorARGB(theme.white) } };
    header.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: colorARGB(theme.deepLagoon) } };
    summaryData.summary.forEach((row) => {
      const excelRow = summarySheet.addRow(row.map((value) => typeof value === 'string' ? escapeSpreadsheetFormula(value) : value));
      const metricFormat = row[2];
      if (metricFormat && metricFormat !== 'percent') excelRow.getCell(2).numFmt = excelNumberFormat(metricFormat);
      if (metricFormat === 'percent') excelRow.getCell(2).numFmt = excelNumberFormat('percent');
    });
  }
  summarySheet.getColumn(1).width = 32;
  summarySheet.getColumn(2).width = 42;
  summarySheet.getColumn(3).width = 18;
  summarySheet.views = [{ state: 'frozen', ySplit: 2 }];
  summarySheet.pageSetup = { paperSize: 9, orientation: 'portrait', fitToPage: true, fitToWidth: 1, fitToHeight: 1 };
  summarySheet.headerFooter.oddFooter = '&LGenerated by OliTechs&RPage &P of &N';

  const names = new Set(['summary']);
  report.sections.filter((section) => section.excel !== false).forEach((section) => {
    let baseName = String(section.name || 'Report').replace(/[\\/*?:\[\]]/g, ' ').slice(0, 31) || 'Report';
    let name = baseName;
    let suffix = 2;
    while (names.has(name.toLowerCase())) {
      const tail = ` ${suffix++}`;
      name = `${baseName.slice(0, 31 - tail.length)}${tail}`;
    }
    names.add(name.toLowerCase());
    addWorksheet(workbook, { ...section, name }, report, theme, section.columns.length > 7);
  });

  const bytes = await workbook.xlsx.writeBuffer();
  return new Blob([bytes], { type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet' });
}

const createFontBase64 = async (provided) => {
  if (provided) return provided;
  if (!fontPromise) {
    fontPromise = (async () => {
      const response = await fetch(REPORT_FONT_URL);
      if (!response.ok) throw new Error('The report font could not be loaded. Please retry the PDF export.');
      const bytes = new Uint8Array(await response.arrayBuffer());
      let binary = '';
      const chunkSize = 0x8000;
      for (let index = 0; index < bytes.length; index += chunkSize) binary += String.fromCharCode(...bytes.subarray(index, index + chunkSize));
      return btoa(binary);
    })().catch((error) => {
      fontPromise = undefined;
      throw error;
    });
  }
  return fontPromise;
};

const pdfCellValue = (column, value) => {
  if (value === null || value === undefined || value === '') return '—';
  if (column.format === 'currency') return `KES ${Number(value || 0).toLocaleString('en-KE', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
  if (column.format === 'number' || column.format === 'quantity') return Number(value || 0).toLocaleString('en-KE', { maximumFractionDigits: 3 });
  if (column.format === 'percent') return `${(Number(value || 0) * 100).toLocaleString('en-KE', { maximumFractionDigits: 1 })}%`;
  if (column.format === 'date' || column.format === 'datetime') {
    const text = value instanceof Date ? value.toISOString() : String(value);
    const date = /^\d{4}-\d{2}-\d{2}$/.test(text) ? new Date(`${text}T12:00:00`) : new Date(text);
    return Number.isNaN(date.getTime()) ? safeReportText(value) : date.toLocaleString('en-KE', column.format === 'date' ? { dateStyle: 'medium', timeZone: 'Africa/Nairobi' } : { dateStyle: 'medium', timeStyle: 'short', timeZone: 'Africa/Nairobi' });
  }
  return safeReportText(value);
};

const buildPdfTotalRow = (columns, rows) => columns.map((column, index) => {
  if (column.total !== 'sum') return index === 0 ? 'Total' : '';
  return rows.reduce((sum, row) => sum + (Number(row[column.key]) || 0), 0);
});

export async function createPdfBlob(definition, { theme: themeOverrides, fontBase64 } = {}) {
  const report = requireReport(definition);
  const theme = resolveReportTheme(themeOverrides);
  const [{ jsPDF }, autoTableModule] = await Promise.all([import('jspdf'), import('jspdf-autotable')]);
  const autoTable = autoTableModule.default || autoTableModule.autoTable;
  const font = await createFontBase64(fontBase64);
  let logoDataUrl = null;
  if (typeof document !== 'undefined' && typeof Image !== 'undefined') {
    try {
      const response = await fetch('/olitechs-logo.svg');
      if (response.ok) {
        const svg = (await response.text())
          .replaceAll('{{COASTAL_TEAL}}', theme.coastalTeal)
          .replaceAll('{{DEEP_LAGOON}}', theme.deepLagoon)
          .replaceAll('{{WHITE}}', theme.white)
          .replaceAll('{{SOFT_WHITE}}', theme.softWhite);
        const objectUrl = URL.createObjectURL(new Blob([svg], { type: 'image/svg+xml' }));
        try {
          const image = new Image();
          await new Promise((resolve, reject) => {
            image.onload = resolve;
            image.onerror = () => reject(new Error('Logo render failed'));
            image.src = objectUrl;
          });
          const canvas = document.createElement('canvas');
          canvas.width = image.naturalWidth || 401;
          canvas.height = image.naturalHeight || 136;
          const context = canvas.getContext('2d');
          if (context) {
            context.drawImage(image, 0, 0, canvas.width, canvas.height);
            logoDataUrl = canvas.toDataURL('image/png');
          }
        } finally {
          URL.revokeObjectURL(objectUrl);
        }
      }
    } catch {
      logoDataUrl = null;
    }
  }
  const pdfSections = report.sections.filter((section) => section.pdf !== false);
  if (!pdfSections.length) throw new Error('This report has no PDF section.');
  const maxColumns = Math.max(...pdfSections.map((section) => section.columns?.length || 0));
  const orientation = maxColumns > 7 ? 'landscape' : 'portrait';
  const pdf = new jsPDF({ orientation, unit: 'mm', format: 'a4', compress: true });
  pdf.addFileToVFS(FONT_VFS_NAME, font);
  pdf.addFont(FONT_VFS_NAME, FONT_FAMILY, 'normal');
  pdf.setFont(FONT_FAMILY, 'normal');
  const rgb = {
    deepLagoon: colorToRgb(theme.deepLagoon),
    coastalTeal: colorToRgb(theme.coastalTeal),
    white: colorToRgb(theme.white),
    softWhite: colorToRgb(theme.softWhite),
    sidebar: colorToRgb(theme.sidebar),
    text: colorToRgb(theme.text),
    accent: colorToRgb(theme.accent),
  };
  const pageHeight = pdf.internal.pageSize.getHeight();
  let cursorY = 50;

  pdfSections.forEach((section) => {
    const columns = section.columns || [];
    if (!columns.length) throw new Error(`Report section “${section.title}” has no columns.`);
    if (cursorY > pageHeight - 34) {
      pdf.addPage();
      cursorY = 42;
    }
    pdf.setFont(FONT_FAMILY, 'normal');
    pdf.setFontSize(10);
    pdf.setTextColor(...rgb.coastalTeal);
    pdf.text(safeReportText(section.title || section.name), 10, cursorY);
    cursorY += 3;
    const body = (section.rows || []).map((row) => columns.map((column) => pdfCellValue(column, row[column.key])));
    const hasTotals = columns.some((column) => column.total === 'sum');
    if (body.length && hasTotals) {
      const totals = buildPdfTotalRow(columns, section.rows);
      body.push(totals.map((value, index) => columns[index].format ? pdfCellValue(columns[index], value) : value));
    } else if (!body.length) {
      body.push(columns.map((_, index) => index === 0 ? 'No transaction data for the selected filters.' : ''));
    }
    const availableWidth = pdf.internal.pageSize.getWidth() - 20;
    const declaredWidth = columns.reduce((sum, column) => sum + Math.min(62, Math.max(12, Number(column.width) || 18)), 0);
    const widthScale = availableWidth / Math.max(1, declaredWidth);
    autoTable(pdf, {
      startY: cursorY,
      margin: { top: 38, right: 10, bottom: 20, left: 10 },
      head: [columns.map((column) => safeReportText(column.label))],
      body,
      theme: 'grid',
      showHead: 'everyPage',
      rowPageBreak: 'avoid',
      styles: { font: FONT_FAMILY, fontStyle: 'normal', fontSize: maxColumns > 7 ? 6.5 : 8, cellPadding: 2, overflow: 'linebreak', textColor: rgb.text, lineColor: rgb.sidebar, lineWidth: 0.15, valign: 'middle' },
      headStyles: { fillColor: rgb.deepLagoon, textColor: rgb.white, font: FONT_FAMILY, fontStyle: 'normal', fontSize: maxColumns > 7 ? 7 : 8 },
      alternateRowStyles: { fillColor: rgb.softWhite },
      bodyStyles: { minCellHeight: 7 },
      columnStyles: Object.fromEntries(columns.map((column, index) => [index, { cellWidth: Math.min(availableWidth / columns.length, Math.min(62, Math.max(12, Number(column.width) || 18)) * widthScale), halign: column.align || (column.type === 'number' ? 'right' : 'left') }])),
      didParseCell: (data) => {
        if (hasTotals && data.row.index === body.length - 1 && (section.rows || []).length && data.section === 'body') {
          data.cell.styles.fillColor = rgb.sidebar;
          data.cell.styles.fontStyle = 'normal';
          data.cell.styles.textColor = rgb.deepLagoon;
        }
      },
    });
    cursorY = (pdf.lastAutoTable?.finalY || cursorY) + 9;
  });

  if (report.notes?.length) {
    const notes = report.notes.map((note) => `• ${safeReportText(note)}`);
    const noteText = notes.join('\n');
    const noteLines = pdf.splitTextToSize(noteText, pdf.internal.pageSize.getWidth() - 20);
    if (cursorY + noteLines.length * 4 > pageHeight - 22) {
      pdf.addPage();
      cursorY = 42;
    }
    pdf.setFontSize(7);
    pdf.setTextColor(...rgb.text);
    pdf.text(noteLines, 10, cursorY + 4);
  }

  const totalPages = pdf.internal.getNumberOfPages();
  for (let page = 1; page <= totalPages; page += 1) {
    pdf.setPage(page);
    const width = pdf.internal.pageSize.getWidth();
    pdf.setFont(FONT_FAMILY, 'normal');
    pdf.setTextColor(...rgb.deepLagoon);
    if (page === 1) {
      if (logoDataUrl) pdf.addImage(logoDataUrl, 'PNG', 10, 5, 40, 13.57);
      else {
        pdf.setFontSize(16);
        pdf.text('OliTechs', 10, 13);
      }
      pdf.setFontSize(11);
      pdf.text(safeReportText(report.title), 10, 21);
      pdf.setFontSize(7.5);
      pdf.setTextColor(...rgb.text);
      const property = safeReportText(report.propertyName || 'OliTechs');
      const period = report.period?.from && report.period?.to ? `${report.period.from} to ${report.period.to}` : 'Current';
      pdf.text(`${property} · ${period}`, 10, 27);
      if (report.subtitle) pdf.text(pdf.splitTextToSize(safeReportText(report.subtitle), width - 20).slice(0, 1), 10, 32);
      const filterText = Object.entries(report.filters || {}).filter(([, value]) => value !== null && value !== undefined && value !== '').map(([key, value]) => `${key}: ${Array.isArray(value) ? value.join(', ') : value}`).join(' · ');
      if (filterText) pdf.text(pdf.splitTextToSize(`Filters · ${safeReportText(filterText)}`, width - 20).slice(0, 1), 10, 36);
      pdf.text(`Generated by ${safeReportText(report.generatedBy || 'Authorized user')} · ${new Date(report.generatedAt || Date.now()).toLocaleString('en-KE', { timeZone: 'Africa/Nairobi' })}`, 10, 41);
    } else {
      pdf.setFontSize(9);
      pdf.text(`OliTechs · ${safeReportText(report.title)}`, 10, 13);
      pdf.setFontSize(7);
      pdf.setTextColor(...rgb.text);
      pdf.text(`${report.period?.from || 'Current'}${report.period?.to ? ` to ${report.period.to}` : ''}`, 10, 19);
    }
    pdf.setDrawColor(...rgb.sidebar);
    pdf.setLineWidth(0.3);
    pdf.line(10, pageHeight - 14, width - 10, pageHeight - 14);
    pdf.setFontSize(7);
    pdf.setTextColor(...rgb.text);
    pdf.text('Generated by OliTechs', 10, pageHeight - 8);
    pdf.text(`Page ${page} of ${totalPages}`, width - 10, pageHeight - 8, { align: 'right' });
  }
  return pdf.output('blob');
}

export function downloadBlob(blob, filename) {
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement('a');
  anchor.href = url;
  anchor.download = filename;
  anchor.rel = 'noopener';
  document.body.appendChild(anchor);
  anchor.click();
  anchor.remove();
  window.setTimeout(() => URL.revokeObjectURL(url), 60_000);
}

export function openPdfPreview(blob, targetWindow) {
  if (!targetWindow || targetWindow.closed) throw new Error('The print-preview window was closed before the PDF was ready.');
  const url = URL.createObjectURL(blob);
  targetWindow.location.replace(url);
  targetWindow.focus();
  targetWindow.setTimeout(() => URL.revokeObjectURL(url), 15 * 60_000);
}

export const reportFilename = (definition, extension) => {
  const name = String(definition?.title || definition?.key || 'Report').replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/[^a-z0-9]+/gi, '-').replace(/^-+|-+$/g, '');
  const from = String(definition?.period?.from || '').replace(/[^0-9-]/g, '');
  const to = String(definition?.period?.to || '').replace(/[^0-9-]/g, '');
  const safeExtension = String(extension || '').toLowerCase().replace(/[^a-z0-9]/g, '') || 'pdf';
  return `OliTechs_${name || 'Report'}${from ? `_${from}` : ''}${to ? `-to-${to}` : ''}.${safeExtension}`;
};
